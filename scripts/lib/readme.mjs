import { resolveIcon } from "./icons.mjs";
import { esc } from "./utils.mjs";

const LABELS = {
  work: "Selected work",
  stack: "Stack",
  activity: "Activity",
  contact: "Contact",
};

function projectCell(project) {
  const name = esc(project.name);
  const icon = resolveIcon(project.icon);
  const url = project.url ? esc(project.url) : "";
  const image = `<img src="assets/projects/${icon}.svg" width="56" height="56" alt="${name}">`;
  const title = url ? `<a href="${url}"><b>${name}</b></a>` : `<b>${name}</b>`;
  const tags = Array.isArray(project.tags) ? project.tags.filter(Boolean).map((tag) => `<code>${esc(tag)}</code>`) : [];
  const chips = [...tags, ...(project.note ? [esc(project.note)] : [])].join(" · ");

  return `    <td width="50%" valign="top" align="center">
      ${url ? `<a href="${url}">${image}</a>` : image}
      <br><br>
      ${title}${project.description ? `<br>
      <sub>${esc(project.description)}</sub>` : ""}${chips ? `<br>
      <sub>${chips}</sub>` : ""}
    </td>`;
}

function projectsTable(projects) {
  const rows = [];
  for (let index = 0; index < projects.length; index += 2) {
    if (rows.length) {
      rows.push(`  <tr>
    <td colspan="2" align="center"><br></td>
  </tr>`);
    }
    rows.push(`  <tr>
${projectCell(projects[index])}
${projects[index + 1] ? projectCell(projects[index + 1]) : '    <td width="50%"></td>'}
  </tr>`);
  }
  return `<table>
${rows.join("\n")}
</table>`;
}

function contactLinks(config) {
  const links = [];
  const seen = new Set();
  const add = (label, url) => {
    if (!label || !url || seen.has(url)) return;
    seen.add(url);
    links.push({ label, url });
  };

  add("GitHub", config.github ? `https://github.com/${config.github}` : "");
  add("Telegram", config.telegram ? `https://t.me/${config.telegram}` : "");
  add("Email", config.email ? `mailto:${config.email}` : "");
  add("Website", config.website || "");
  for (const link of config.links || []) add(link.label, link.url);

  return links;
}

export function renderReadme(config) {
  const labels = { ...LABELS, ...(config.labels || {}) };
  const name = String(config.name || "Your name").trim();
  const projects = Array.isArray(config.projects) ? config.projects.filter((project) => project?.name) : [];
  const stack = Array.isArray(config.stack) ? config.stack.filter((row) => row?.label) : [];
  const links = contactLinks(config);
  const statUser = config.stats?.username || config.github || "your profile";
  const githubUrl = config.github ? `https://github.com/${config.github}` : "";
  const rule = `<div align="center">
  <img src="assets/rule.svg" width="100%" alt="">
</div>`;

  const nav = [];
  if (projects.length) nav.push(`<a href="#selected-work">${esc(labels.work)}</a>`);
  if (stack.length) nav.push(`<a href="#stack">${esc(labels.stack)}</a>`);
  nav.push(`<a href="#activity">${esc(labels.activity)}</a>`);
  if (links.length) nav.push(`<a href="#contact">${esc(labels.contact)}</a>`);

  const chunks = [];

  chunks.push(`<!-- Generated by Noir — edit profile.config.json instead of this file. -->

<div align="center">
  ${githubUrl ? `<a href="${esc(githubUrl)}">` : ""}
    <img src="assets/hero.svg" alt="${esc(name)} — ${esc(String(config.role || "software developer").toLowerCase())}" width="100%">
  ${githubUrl ? "</a>" : ""}
</div>

<p align="center">
  ${nav.join(" &nbsp;·&nbsp; ")}
</p>`);

  if (config.bio) chunks.push(esc(config.bio));
  if (config.now) chunks.push(`> ${esc(config.now)}`);

  if (projects.length) {
    const count = String(projects.length).padStart(2, "0");
    chunks.push(rule);
    chunks.push(`## ${esc(labels.work)} <sub>${count}</sub>

${projectsTable(projects)}`);

    if (config.projectsNote) {
      chunks.push(`<p align="center">
  <sub>${esc(config.projectsNote)}</sub>
</p>`);
    }
  }

  if (stack.length) {
    const rows = stack
      .map(
        (row) => `  <tr>
    <td width="130" valign="top"><b>${esc(row.label)}</b></td>
    <td valign="top"><sub>${(row.items || []).map(esc).join(" · ")}</sub></td>
  </tr>`,
      )
      .join("\n");

    chunks.push(rule);
    chunks.push(`## ${esc(labels.stack)}

<table>
${rows}
</table>`);
  }

  chunks.push(rule);
  chunks.push(`## ${esc(labels.activity)} <sub>live</sub>

<p align="center">
  ${githubUrl ? `<a href="${esc(githubUrl)}">` : ""}
    <img src="assets/stats.svg" alt="Live GitHub metrics for ${esc(statUser)}" width="100%">
  ${githubUrl ? "</a>" : ""}
</p>`);

  if (links.length) {
    const contact = links.map((link) => `<a href="${esc(link.url)}"><b>${esc(link.label)}</b></a>`).join(" &nbsp;·&nbsp; ");
    chunks.push(rule);
    chunks.push(`<a id="contact"></a>

<p align="center">
  ${contact}
</p>`);
  }

  if (config.footerNote) {
    chunks.push(`<p align="center">
  <sub>${esc(config.footerNote)}</sub>
</p>`);
  }

  const footer = [];
  if (config.copyright) footer.push(esc(config.copyright));
  if (config.credit?.label && config.credit?.url) {
    footer.push(`Built with <a href="${esc(config.credit.url)}">${esc(config.credit.label)}</a>`);
  }
  if (footer.length) {
    chunks.push(`<p align="center">
  <sub>${footer.join(" · ")}</sub>
</p>`);
  }

  return `${chunks.join("\n\n")}\n`;
}
